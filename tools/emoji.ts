// Writes android/assets/emoji.txt from Unicode's emoji-test.txt: one line per group, emoji split by spaces.
// Usage: bun tools/emoji.ts path/to/emoji-test.txt
// Get the source from https://unicode.org/Public/emoji/<version>/emoji-test.txt.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const source = process.argv[2];
if (!source) throw new Error("Pass the path to emoji-test.txt");

const text = readFileSync(source, "utf8");
const version = text.match(/^# Version: (\S+)/m)?.[1] ?? "unknown";
const groups = new Map<string, string[]>();
let group = "";
for (const line of text.split(/\r?\n/)) {
  const heading = line.match(/^# group: (.+)$/);
  if (heading) group = heading[1];
  const entry = line.match(/^([0-9A-F ]+);\s*fully-qualified\s*#/);
  if (!entry || group === "Component") continue;
  const codes = entry[1].trim().split(" ").map((code) => parseInt(code, 16));
  // Skin tones are variants of an emoji already in the list.
  if (codes.some((code) => code >= 0x1f3fb && code <= 0x1f3ff)) continue;
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group)!.push(String.fromCodePoint(...codes));
}

const lines = [`# Generated by tools/emoji.ts from Unicode emoji-test.txt ${version}.`];
for (const [name, emoji] of groups) lines.push(`${name}\t${emoji.join(" ")}`);
writeFileSync(join(import.meta.dir, "../android/assets/emoji.txt"), lines.join("\n") + "\n");
console.log([...groups].map(([name, emoji]) => `${name}: ${emoji.length}`).join("\n"));
