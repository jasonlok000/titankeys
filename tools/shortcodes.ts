// Writes android/assets/shortcodes.txt from gemoji's emoji.json: one emoji per line, then its shortcode names.
// Usage: bun tools/shortcodes.ts path/to/emoji.json [gemoji commit]
// Get the source from https://github.com/github/gemoji/blob/master/db/emoji.json. gemoji is MIT, see licences/gemoji-MIT.txt.
// The names are English. Another language would get a list of its own, next to this one.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const source = process.argv[2];
if (!source) throw new Error("Pass the path to emoji.json");
const commit = process.argv[3] ?? "unknown";

type Entry = { emoji: string; aliases: string[] };
const entries = JSON.parse(readFileSync(source, "utf8")) as Entry[];
const valid = /^[a-z0-9_+-]{1,40}$/;
const lines = [`# Generated by tools/shortcodes.ts from gemoji ${commit} (MIT). One emoji, then its names.`];
let names = 0;
for (const { emoji, aliases } of entries) {
  const usable = aliases.map(name => name.toLowerCase()).filter(name => valid.test(name));
  if (!usable.length) continue;
  lines.push(`${emoji} ${usable.join(" ")}`);
  names += usable.length;
}
writeFileSync(join(import.meta.dir, "../android/assets/shortcodes.txt"), lines.join("\n") + "\n");
console.log(`${lines.length - 1} emoji, ${names} names`);
